"""Generate the lazy-registration catalog without importing desktop or MCP runtime."""
import ast
import json
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'win-desktop-control/src/wdc'

def catalog():
    specs = runpy.run_path(str(SOURCE / 'schemas.py'))['tool_specs']()
    tree = ast.parse((SOURCE / 'mcp_server.py').read_text(encoding='utf-8'))
    instructions = next(ast.literal_eval(node.value) for node in tree.body
                        if isinstance(node, ast.Assign)
                        and any(isinstance(t, ast.Name) and t.id == 'INSTRUCTIONS' for t in node.targets))
    return {'version': 1, 'instructions': instructions, 'tools': [
        {'name': spec['name'], 'description': spec['description'], 'inputSchema': spec['parameters']}
        for spec in specs]}

def render():
    return '// Generated by scripts/build-tool-catalog.py; checked by isolated tests.\nexport const TOOL_CATALOG = ' + json.dumps(catalog(), ensure_ascii=False, indent=2) + ';\n'

if __name__ == '__main__':
    (ROOT / 'dsh-wdc-computer-use/lib/tool-catalog.js').write_text(render(), encoding='utf-8')
